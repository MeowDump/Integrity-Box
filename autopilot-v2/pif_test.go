func pifEngine(t *testing.T, pifText, patchText string) (*Engine, string, string) {
	t.Helper()
	dir := t.TempDir()
	mod := filepath.Join(dir, "module")
	ts := filepath.Join(dir, "ts")
	for _, d := range []string{mod, ts} {
		if err := os.MkdirAll(d, 0755); err != nil {
			t.Fatal(err)
		}
	}
	propPath, patchPath := filepath.Join(mod, "custom.pif.prop"), filepath.Join(ts, "security_patch.txt")
	if pifText != "" {
		if err := os.WriteFile(propPath, []byte(pifText), 0644); err != nil {
			t.Fatal(err)
		}
	}
	if patchText != "" {
		if err := os.WriteFile(patchPath, []byte(patchText), 0640); err != nil {
			t.Fatal(err)
		}
	}
	e := &Engine{moduleRoot: mod, root: ts, ram: dir, brain: dir, policy: defaultPolicy()}
	// The fixtures describe the incident of 2026-11-16 (fingerprints valid until 2026-11-27): the wall clock must not
	// decide whether they are "expiring". A test that needs another day sets e.clock itself.
	e.clock = func() time.Time { return time.Date(2026, 11, 17, 12, 0, 0, 0, time.UTC) }
	return e, propPath, patchPath
}

// The incident, replayed: PIF spoofs 2026-11-05 while Tricky Store attests 2026-10-05.
func TestIncidentPatchMismatchIsDetectedAndRepaired(t *testing.T) {
	e, _, patchPath := pifEngine(t, strings.Replace(octoberPIF, "SECURITY_PATCH=2026-10-05", "SECURITY_PATCH=2026-11-05", 1), "all=2026-10-05\n")
	f, pf := e.pifAudit(true)
	if e.status.PIF.PatchPair != "mismatch" {
		t.Fatalf("pair = %s, want mismatch", e.status.PIF.PatchPair)
	}
	if err := e.pifSyncPatch(f, pf); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(patchPath)
	if string(b) != "all=2026-11-05\n" {
		t.Fatalf("patch file = %q", b)
	}
	if e.status.PIF.PatchPair != "match" || e.status.PIF.Action != "patch_synced" {
		t.Fatalf("status after repair: %+v", e.status.PIF)
	}
	st, _ := os.Stat(patchPath)
	if st.Mode().Perm() != 0640 {
		t.Fatalf("mode must be preserved, got %v", st.Mode().Perm())
	}
	if m, _ := filepath.Glob(filepath.Join(filepath.Dir(patchPath), ".autopilot-*")); len(m) != 0 {
		t.Fatalf("leftover temp files: %v", m)
	}
	// second cycle is a no-op
	f, pf = e.pifAudit(true)
	before, _ := os.Stat(patchPath)
	_ = e.pifSyncPatch(f, pf)
	after, _ := os.Stat(patchPath)
	if !before.ModTime().Equal(after.ModTime()) {
		t.Fatal("matching files must not be rewritten")
	}
}

func TestPatchSyncLeavesAloneWhatItMust(t *testing.T) {
	mismatched := strings.Replace(octoberPIF, "SECURITY_PATCH=2026-10-05", "SECURITY_PATCH=2026-11-05", 1)
	cases := []struct {
		name  string
		pif   string
		patch string
		mod   func(e *Engine)
	}{
		{"manual mode", mismatched, "all=2026-10-05\n", func(e *Engine) { e.policy.PIF.Mode = "manual" }},
		{"off mode", mismatched, "all=2026-10-05\n", func(e *Engine) { e.policy.PIF.Mode = "off" }},
		{"sync disabled", mismatched, "all=2026-10-05\n", func(e *Engine) { e.policy.PIF.SyncPatch = false }},
		{"dry run", mismatched, "all=2026-10-05\n", func(e *Engine) { e.dryRun = true }},
		{"stock mode is intentional", mismatched, "system=prop\n", nil},
		{"missing patch file is not created", mismatched, "", nil},
		{"invalid fingerprint", strings.Replace(mismatched, "ID=ZP11.260918.007", "ID=ZP11.000000.000", 1), "all=2026-10-05\n", nil},
		{"no fingerprint", "", "all=2026-10-05\n", nil},
		{"unknown patch format", mismatched, "boot=whatever\n", nil},
	}
	for _, c := range cases {
		e, _, patchPath := pifEngine(t, c.pif, c.patch)
		if c.mod != nil {
			c.mod(e)
		}
		f, pf := e.pifAudit(true)
		if err := e.pifSyncPatch(f, pf); err != nil {
			t.Errorf("%s: %v", c.name, err)
		}
		b, _ := os.ReadFile(patchPath)
		if string(b) != c.patch {
			t.Errorf("%s: file changed to %q", c.name, b)
		}
	}
}

