func mustPIF(t *testing.T, s string) pifFile {
	t.Helper()
	f, err := parsePIF([]byte(s))
	if err != nil {
		t.Fatalf("parsePIF: %v", err)
	}
	return f
}

func TestParsePIFRealFiles(t *testing.T) {
	f := mustPIF(t, octoberPIF)
	if f.patch() != "2026-10-05" || f.Props["ID"] != "ZP11.260918.007" {
		t.Fatalf("props: %v", f.Props)
	}
	if f.Released.Format("2006-01-02") != "2026-10-07" || f.Expires.Format("2006-01-02") != "2026-11-17" {
		t.Fatalf("comments: %v %v", f.Released, f.Expires)
	}
	if !strings.HasPrefix(f.Tail, "# Configuration") || !strings.Contains(f.Tail, "verboseLogs=0") {
		t.Fatalf("tail lost: %q", f.Tail)
	}
	if strings.Contains(f.Tail, "Estimated Expiry") || strings.Contains(f.Tail, "Generated by") {
		t.Fatalf("AutoPilot-owned comments must not stay in the tail: %q", f.Tail)
	}
	n := mustPIF(t, novemberMeow) // upstream file has no configuration section
	if n.Tail != "" || n.patch() != "2026-11-05" {
		t.Fatalf("meow.prop: %+v", n)
	}
}

func TestParsePIFRejects(t *testing.T) {
	replace := func(old, new string) string { return strings.Replace(novemberMeow, old, new, 1) }
	cases := map[string]string{
		"fingerprint disagrees with ID":      replace("ID=ZP11.261016.008", "ID=ZP11.260918.007"),
		"fingerprint disagrees with PRODUCT": replace("PRODUCT=bluejay_beta", "PRODUCT=cubs_beta"),
		"missing key":                        strings.Replace(novemberMeow, "MODEL=Pixel 6a\n", "", 1),
		"bad patch format":                   replace("SECURITY_PATCH=2026-11-05", "SECURITY_PATCH=2026-11"),
		"patch year":                         replace("SECURITY_PATCH=2026-11-05", "SECURITY_PATCH=1999-11-05"),
		"shell metacharacters":               replace("MODEL=Pixel 6a", "MODEL=Pixel $(id)"),
		"quote":                              replace("MODEL=Pixel 6a", `MODEL=Pixel "6a"`),
		"duplicate key":                      novemberMeow + "MODEL=Other\n",
		"fingerprint shape":                  replace("FINGERPRINT=google/bluejay_beta/bluejay:CANARY/ZP11.261016.008/16754936:user/release-keys", "FINGERPRINT=google/bluejay"),
		"lowercase key":                      novemberMeow + "model=x\n",
	}
	for name, text := range cases {
		if _, err := parsePIF([]byte(text)); err == nil {
			t.Errorf("%s: must be rejected", name)
		}
	}
	if _, err := parsePIF([]byte(strings.Repeat("A=1\n", pifMaxBytes))); err == nil {
		t.Error("oversized file must be rejected")
	}
	if _, err := parsePIF([]byte(strings.ReplaceAll(novemberMeow, "\n", "\r\n"))); err != nil {
		t.Errorf("CRLF must be accepted: %v", err)
	}
}

func TestClassifyPIFDecisionTable(t *testing.T) {
	now := time.Date(2026, 11, 16, 12, 0, 0, 0, time.UTC)
	pol := defaultPIFPolicy()
	old := mustPIF(t, octoberPIF)     // expires 2026-11-17: 12 h left
	fresh := mustPIF(t, novemberMeow) // no comments: unknown expiry
	fresh.Released = time.Date(2026, 11, 14, 0, 0, 0, 0, time.UTC)
	banned := map[string]bool{"ZP11.260918.007": true}
	cases := []struct {
		name   string
		f      pifFile
		err    error
		absent bool
		timeOK bool
		ban    map[string]bool
		want   string
	}{
		{"absent", pifFile{}, nil, true, true, nil, "absent"},
		{"invalid", pifFile{}, os.ErrInvalid, false, true, nil, "invalid"},
		{"banned wins over expiring", old, nil, false, true, banned, "banned"},
		{"banned even with unknown clock", old, nil, false, false, banned, "banned"},
		{"inside the renew window", old, nil, false, true, nil, "expiring"}, // 12 h < 72 h
		{"expired for real", mustPIFExpiring(t, "2026-11-10"), nil, false, true, nil, "expired"},
		{"clock unknown: no expiry judgement", old, nil, false, false, nil, "ok"},
		{"fresh by release + lifetime", fresh, nil, false, true, nil, "ok"},
		{"no comments: expiry from the build id (2026-10-16 + 42d)", mustPIF(t, novemberMeow), nil, false, true, nil, "ok"},
		{"banned by fingerprint string", fresh, nil, false, true, map[string]bool{fresh.Props["FINGERPRINT"]: true}, "banned"},
	}
	for _, c := range cases {
		if got := classifyPIF(c.f, c.err, c.absent, now, c.timeOK, pol, c.ban); got != c.want {
			t.Errorf("%s: got %s want %s", c.name, got, c.want)
		}
	}
}

