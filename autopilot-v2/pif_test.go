func TestPatchFileFormatsAndPairs(t *testing.T) {
	cases := []struct {
		text, kind, value, pair string
	}{
		{"all=2026-11-05\n", "all", "2026-11-05", "match"},
		{"all=2026-10-05\n", "all", "2026-10-05", "mismatch"},
		{"2026-11-05\n", "date", "2026-11-05", "match"},
		{"20261105\n", "date8", "2026-11-05", "match"},
		{"20261005\n", "date8", "2026-10-05", "mismatch"},
		{"system=202611\n", "system", "2026-11", "match"},
		{"system=202610\n", "system", "2026-10", "mismatch"},
		{"system=prop\n", "stock", "", "stock"},
		{"all=prop\n", "stock", "", "stock"},
		{"# comment\n\n", "unknown", "", "unknown"},
		{"all=garbage\n", "unknown", "", "unknown"},
		{"all=2026-11-05\r\nsystem=202610\r\n", "all", "2026-11-05", "match"}, // "all" wins, CRLF tolerated
	}
	for _, c := range cases {
		pf := parsePatchFile([]byte(c.text))
		if pf.Kind != c.kind || pf.Value != c.value || pf.pair("2026-11-05") != c.pair {
			t.Errorf("%q: got %+v pair %s, want %s %s %s", c.text, pf, pf.pair("2026-11-05"), c.kind, c.value, c.pair)
		}
	}
	if parsePatchFile(nil).pair("2026-11-05") != "missing" {
		t.Error("absent file must be reported as missing")
	}
}

func TestWithPatchKeepsFormatAndOtherLines(t *testing.T) {
	cases := []struct{ in, want string }{
		{"all=2026-10-05\n", "all=2026-11-05\n"},
		{"2026-10-05\n", "2026-11-05\n"},
		{"20261005\n", "20261105\n"},
		{"system=202610\n", "system=202611\n"},
		{"# keep me\nall=2026-10-05\nboot=2026-01-01\n", "# keep me\nall=2026-11-05\nboot=2026-01-01\n"},
	}
	for _, c := range cases {
		pf := parsePatchFile([]byte(c.in))
		if got := string(pf.withPatch([]byte(c.in), "2026-11-05")); got != c.want {
			t.Errorf("%q -> %q, want %q", c.in, got, c.want)
		}
	}
	empty := parsePatchFile([]byte("# nothing\n"))
	if got := string(empty.withPatch([]byte("# nothing\n"), "2026-11-05")); got != "all=2026-11-05\n" {
		t.Errorf("unusable file is replaced by a canonical one: %q", got)
	}
}

