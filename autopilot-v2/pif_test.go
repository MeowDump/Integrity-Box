func TestPIFPolicyKeysAreClamped(t *testing.T) {
	p, notes := parsePolicy("pif_mode = Manual\npif_renew_before_hours = 5\npif_lifetime_days = 400\npif_probe_wait_seconds=abc\npif_follow_latest=yes\npif_sync_patch=off\npif_sources = archive, bogus, google\npif_mode_typo=1\n")
	if p.PIF.Mode != "manual" || p.PIF.RenewBefore != 24*time.Hour || p.PIF.Lifetime != 90*24*time.Hour || !p.PIF.FollowLatest || p.PIF.SyncPatch {
		t.Fatalf("policy: %+v", p.PIF)
	}
	if p.PIF.ProbeWait != 15*time.Second {
		t.Fatalf("bad number keeps the default, got %v", p.PIF.ProbeWait)
	}
	if len(p.PIF.Sources) != 2 || p.PIF.Sources[0] != "archive" || p.PIF.Sources[1] != "google" {
		t.Fatalf("sources: %v", p.PIF.Sources)
	}
	if len(notes) < 4 {
		t.Fatalf("every skipped or clamped line must be reported: %v", notes)
	}
	if bad, _ := parsePolicy("pif_mode=banana\n"); bad.PIF.Mode != "auto" {
		t.Fatalf("invalid mode keeps auto, got %s", bad.PIF.Mode)
	}
}

func TestClassifyPIFExpiryBoundaries(t *testing.T) {
	pol := defaultPIFPolicy() // renew window 72 h
	f := mustPIFExpiring(t, "2026-11-17")
	exp := time.Date(2026, 11, 17, 0, 0, 0, 0, time.UTC)
	cases := []struct {
		now  time.Time
		want string
	}{
		{exp.Add(-72*time.Hour - time.Second), "ok"},
		{exp.Add(-72 * time.Hour), "expiring"}, // exactly the window edge: 72h is not < 72h, see below
		{exp.Add(-time.Second), "expiring"},
		{exp, "expired"}, // the expiry instant itself is already expired
		{exp.Add(24 * time.Hour), "expired"},
	}
	// The window edge: Sub == RenewBefore is NOT "< RenewBefore", so exactly 72 h left is still ok.
	cases[1].want = "ok"
	for _, c := range cases {
		if got := classifyPIF(f, nil, false, c.now, true, pol, nil); got != c.want {
			t.Errorf("now=%s: got %s want %s", c.now.Format(time.RFC3339), got, c.want)
		}
	}
}

func TestReleaseDateFallsBackToBuildID(t *testing.T) {
	f := mustPIF(t, novemberMeow) // ZP11.261016.008, no comments
	if got := f.releaseDate().Format("2006-01-02"); got != "2026-10-16" {
		t.Fatalf("release from build id = %s", got)
	}
	if got := f.expiry(42 * 24 * time.Hour).Format("2006-01-02"); got != "2026-11-27" {
		t.Fatalf("expiry = %s", got)
	}
	f.Released = time.Date(2026, 10, 20, 0, 0, 0, 0, time.UTC) // an explicit comment wins
	if got := f.releaseDate().Format("2006-01-02"); got != "2026-10-20" {
		t.Fatalf("explicit release must win, got %s", got)
	}
	g := mustPIF(t, strings.ReplaceAll(novemberMeow, "ZP11.261016.008", "BUILD-X"))
	if !g.releaseDate().IsZero() || !g.expiry(time.Hour).IsZero() {
		t.Fatal("an id without a date leaves the expiry unknown")
	}
	// the clock gate: 2026-11-26 is inside the 72h window, 2026-11-27 is expired
	pol := defaultPIFPolicy()
	if s := classifyPIF(mustPIF(t, novemberMeow), nil, false, time.Date(2026, 11, 25, 0, 0, 0, 0, time.UTC), true, pol, nil); s != "expiring" {
		t.Fatalf("2026-11-25 -> %s, want expiring (72h window)", s)
	}
}

func TestPatchFilePrecedenceDoesNotDependOnLineOrder(t *testing.T) {
	cases := []struct{ text, kind, value string }{
		{"system=prop\nsystem=202611\n", "system", "2026-11"},
		{"system=202611\nsystem=prop\n", "system", "2026-11"},
		{"2026-10-05\nall=2026-11-05\n", "all", "2026-11-05"},
		{"all=2026-11-05\n2026-10-05\n", "all", "2026-11-05"},
		{"system=202610\n2026-11-05\n", "date", "2026-11-05"},
		{"all=prop\nsystem=202611\n", "system", "2026-11"},
		{"all=2026-10-05\nall=2026-11-05\n", "all", "2026-11-05"},
		{"all=2026-11-05\nall=2026-10-05\n", "all", "2026-10-05"}, // the LAST line of a kind wins
		{"all = 2026-11-05\n", "all", "2026-11-05"},               // whitespace around the key and the value is ignored
		{"all\t=\t20261105\r\n", "all", "2026-11-05"},
		{"vendor=2026-11-05\n", "unknown", ""},
	}
	for _, c := range cases {
		if pf := parsePatchFile([]byte(c.text)); pf.Kind != c.kind || pf.Value != c.value {
			t.Errorf("%q -> %+v, want %s %s", c.text, pf, c.kind, c.value)
		}
	}
}

