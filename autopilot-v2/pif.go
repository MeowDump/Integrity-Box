package main

// PIF fingerprint contour. The keybox contour answers "is the key
// valid and accepted"; this one keeps the OTHER half of the attestation triplet consistent:
// the Pixel Canary fingerprint that Play Integrity Fork spoofs (custom.pif.prop) and the
// security patch Tricky Store attests (security_patch.txt). The invariant this file owns:
// security_patch.txt must equal SECURITY_PATCH of the active fingerprint.

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"time"
)

const pifMaxBytes = 16 << 10

var (
	pifRequired = []string{"MANUFACTURER", "MODEL", "FINGERPRINT", "BRAND", "PRODUCT", "DEVICE", "RELEASE", "ID", "INCREMENTAL", "TYPE", "TAGS", "SECURITY_PATCH"}
	// Canonical order of the fingerprint block that AutoPilot writes (PIF reads any order).
	pifBlockOrder = []string{"MANUFACTURER", "MODEL", "FINGERPRINT", "BRAND", "PRODUCT", "DEVICE", "RELEASE", "ID", "INCREMENTAL", "TYPE", "TAGS", "SECURITY_PATCH", "DEVICE_INITIAL_SDK_INT"}
	pifValue      = regexp.MustCompile(`^[A-Za-z0-9 ._:/+()-]{1,200}$`)
	pifKey        = regexp.MustCompile(`^[A-Z_]{2,40}$`)
	pifDate       = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}$`)
	pifComment    = regexp.MustCompile(`^#\s*(Canary Released|Estimated Expiry):\s*(\d{4}-\d{2}-\d{2})\s*$`)
)

// pifFile is a parsed custom.pif.prop: the fingerprint block plus the untouched configuration tail.
type pifFile struct {
	Props    map[string]string
	Released time.Time // zero when unknown
	Expires  time.Time // zero when unknown
	Tail     string    // everything from "# Configuration" on, minus AutoPilot-owned comments
}

func parsePIF(b []byte) (pifFile, error) {
	f := pifFile{Props: map[string]string{}}
	if len(b) > pifMaxBytes {
		return f, errors.New("pif file byte limit")
	}
	text := strings.ReplaceAll(string(b), "\r\n", "\n")
	inTail := false
	var tail []string
	for _, raw := range strings.Split(text, "\n") {
		line := strings.TrimRight(raw, " \t")
		if m := pifComment.FindStringSubmatch(strings.TrimSpace(line)); m != nil {
			if t, err := time.Parse("2006-01-02", m[2]); err == nil {
				if m[1] == "Canary Released" {
					f.Released = t
				} else {
					f.Expires = t
				}
			}
			continue // AutoPilot-owned: regenerated on install
		}
		if strings.HasPrefix(line, "# Generated by") || strings.HasPrefix(line, "# Updated by") {
			continue
		}
		if strings.TrimSpace(line) == "# Configuration" {
			inTail = true
		}
		if inTail {
			tail = append(tail, line)
			continue
		}
		s := strings.TrimSpace(line)
		if s == "" || strings.HasPrefix(s, "#") {
			continue
		}
		eq := strings.IndexByte(s, '=')
		if eq < 0 {
			continue
		}
		k, v := s[:eq], strings.TrimSpace(s[eq+1:])
		if !pifKey.MatchString(k) {
			return f, fmt.Errorf("invalid key %q", k)
		}
		if !pifValue.MatchString(v) {
			return f, fmt.Errorf("%s: invalid value", k)
		}
		if _, dup := f.Props[k]; dup {
			return f, fmt.Errorf("%s: duplicated", k)
		}
		f.Props[k] = v
	}
	f.Tail = strings.TrimRight(strings.Join(tail, "\n"), "\n")
	if err := f.check(); err != nil {
		return f, err
	}
	return f, nil
}

// check enforces invariant I-FP: required fields exist and the FINGERPRINT agrees with them.
func (f pifFile) check() error {
	for _, k := range pifRequired {
		if f.Props[k] == "" {
			return fmt.Errorf("%s missing", k)
		}
	}
	// brand/product/device:release/id/incremental:type/tags
	p := strings.Split(f.Props["FINGERPRINT"], "/")
	if len(p) != 6 {
		return errors.New("FINGERPRINT shape")
	}
	devRel := strings.SplitN(p[2], ":", 2)
	incType := strings.SplitN(p[4], ":", 2)
	if len(devRel) != 2 || len(incType) != 2 {
		return errors.New("FINGERPRINT shape")
	}
	pairs := [][2]string{{p[0], f.Props["BRAND"]}, {p[1], f.Props["PRODUCT"]}, {devRel[0], f.Props["DEVICE"]}, {devRel[1], f.Props["RELEASE"]},
		{p[3], f.Props["ID"]}, {incType[0], f.Props["INCREMENTAL"]}, {incType[1], f.Props["TYPE"]}, {p[5], f.Props["TAGS"]}}
	names := []string{"BRAND", "PRODUCT", "DEVICE", "RELEASE", "ID", "INCREMENTAL", "TYPE", "TAGS"}
	for i, pr := range pairs {
		if !strings.EqualFold(pr[0], pr[1]) {
			return fmt.Errorf("FINGERPRINT disagrees with %s", names[i])
		}
	}
	for _, k := range []string{"ID", "FINGERPRINT", "INCREMENTAL", "PRODUCT", "DEVICE"} {
		if strings.Contains(f.Props[k], " ") { // a space shifts the fields the shell doctor reads
			return fmt.Errorf("%s contains a space", k)
		}
	}
	if !pifDate.MatchString(f.Props["SECURITY_PATCH"]) {
		return errors.New("SECURITY_PATCH format")
	}
	t, err := time.Parse("2006-01-02", f.Props["SECURITY_PATCH"])
	if err != nil || t.Year() < 2020 || t.Year() > 2100 {
		return errors.New("SECURITY_PATCH range")
	}
	return nil
}

func (f pifFile) patch() string { return f.Props["SECURITY_PATCH"] }

// render builds a new custom.pif.prop: the fingerprint block, the preserved configuration tail
// (invariant I-CONFIG) and fresh AutoPilot-owned comments.
func (f pifFile) render(tail string, released, expires time.Time, today string) []byte {
	var b strings.Builder
	for _, k := range pifBlockOrder {
		if v, ok := f.Props[k]; ok {
			b.WriteString(k + "=" + v + "\n")
		}
	}
	if tail != "" {
		b.WriteString("\n" + tail + "\n")
	}
	if !released.IsZero() {
		b.WriteString("\n# Canary Released: " + released.Format("2006-01-02") + "\n")
	}
	if !expires.IsZero() {
		b.WriteString("\n# Estimated Expiry: " + expires.Format("2006-01-02") + "\n")
	}
	b.WriteString("\n# Updated by AutoPilot on " + today + "\n")
	return []byte(b.String())
}

var pifBuildDate = regexp.MustCompile(`\.(\d{2})(\d{2})(\d{2})\.`)

// releaseDate is the explicit "Canary Released" comment, else the date embedded in the Google
// build id (ZP11.261016.008 = 2026-10-16). The build date is a LOWER bound of the release:
// Canary images appear up to weeks later (one measured case: 19 days), so the derived expiry
// is early, never late: the contour may look for a replacement sooner, never too late.
func (f pifFile) releaseDate() time.Time {
	if !f.Released.IsZero() {
		return f.Released
	}
	m := pifBuildDate.FindStringSubmatch(f.Props["ID"])
	if m == nil {
		return time.Time{}
	}
	t, err := time.Parse("2006-01-02", "20"+m[1]+"-"+m[2]+"-"+m[3])
	if err != nil {
		return time.Time{}
	}
	return t
}

// expiry returns the best known end of life: the explicit comment, else release + lifetime.
func (f pifFile) expiry(lifetime time.Duration) time.Time {
	r := f.releaseDate()
	if !f.Expires.IsZero() {
		// A claimed end of life far beyond release + lifetime is not believed (a hostile or broken
		// comment must not make a fingerprint look permanent).
		if !r.IsZero() && f.Expires.After(r.Add(2*lifetime)) {
			return r.Add(lifetime)
		}
		return f.Expires
	}
	if !r.IsZero() {
		return r.Add(lifetime)
	}
	return time.Time{}
}

// ---- security_patch.txt (Tricky Store) ----

type patchFile struct {
	Kind  string // all | date | date8 | system | stock | none | unknown
	Value string // YYYY-MM-DD (all/date/date8), YYYY-MM (system), "" otherwise
}

var (
	patchEight = regexp.MustCompile(`^\d{8}$`)
	patchSix   = regexp.MustCompile(`^\d{6}$`)
)

func normalizeDate(v string) (string, string) {
	switch {
	case pifDate.MatchString(v):
		return v, "date"
	case patchEight.MatchString(v):
		return v[:4] + "-" + v[4:6] + "-" + v[6:], "date8"
	}
	return "", ""
}

// patchLine splits a security_patch.txt line into a trimmed key ("" for a bare value) and value.
func patchLine(raw string) (key, val string, ok bool) {
	s := strings.TrimSpace(strings.ReplaceAll(raw, "\r", ""))
	if s == "" || strings.HasPrefix(s, "#") {
		return "", "", false
	}
	if eq := strings.IndexByte(s, '='); eq >= 0 {
		return strings.TrimSpace(s[:eq]), strings.TrimSpace(s[eq+1:]), true
	}
	return "", s, true
}

// parsePatchFile reads the patch Tricky Store attests. Precedence is fixed and independent of line
// order (the doctor's awk uses the same): all= > bare date > system=YYYYMM > stock (=prop); the last
// line of a kind wins.
func parsePatchFile(b []byte) patchFile {
	if b == nil {
		return patchFile{Kind: "none"}
	}
	var all, date, dateKind, sys string
	stock := false
	for _, raw := range strings.Split(string(b), "\n") {
		key, val, ok := patchLine(raw)
		if !ok {
			continue
		}
		switch key {
		case "":
			if v, kind := normalizeDate(val); v != "" {
				date, dateKind = v, kind
			}
		case "all":
			if v, _ := normalizeDate(val); v != "" {
				all = v
			} else if val == "prop" {
				stock = true
			}
		case "system":
			if val == "prop" {
				stock = true
			} else if patchSix.MatchString(val) {
				sys = val[:4] + "-" + val[4:]
			}
		}
	}
	switch {
	case all != "":
		return patchFile{Kind: "all", Value: all}
	case date != "":
		return patchFile{Kind: dateKind, Value: date}
	case sys != "":
		return patchFile{Kind: "system", Value: sys}
	case stock:
		return patchFile{Kind: "stock"}
	}
	return patchFile{Kind: "unknown"}
}

// pair compares the Tricky Store patch with the PIF patch (invariant I-PATCH).
func (p patchFile) pair(pifPatch string) string {
	switch p.Kind {
	case "none":
		return "missing"
	case "stock":
		return "stock"
	case "unknown":
		return "unknown"
	case "system":
		if len(pifPatch) >= 7 && pifPatch[:7] == p.Value {
			return "match"
		}
		return "mismatch"
	}
	if p.Value == pifPatch {
		return "match"
	}
	return "mismatch"
}

// withPatch rewrites only the lines that decide the patch (every line of the winning kind), keeps
// every other line, or creates "all=DATE" when there is no usable line. Each line keeps its own format.
func (p patchFile) withPatch(orig []byte, pifPatch string) []byte {
	if p.Kind == "none" || p.Kind == "unknown" || p.Kind == "stock" || len(strings.TrimSpace(string(orig))) == 0 {
		return []byte("all=" + pifPatch + "\n")
	}
	lines := strings.Split(strings.ReplaceAll(string(orig), "\r", ""), "\n")
	replaced := false
	for i, raw := range lines {
		key, val, ok := patchLine(raw)
		if !ok {
			continue
		}
		switch {
		case p.Kind == "all" && key == "all":
			if v, _ := normalizeDate(val); v != "" {
				lines[i], replaced = "all="+pifPatch, true
			}
		case (p.Kind == "date" || p.Kind == "date8") && key == "":
			if v, kind := normalizeDate(val); v != "" {
				if kind == "date8" {
					lines[i] = strings.ReplaceAll(pifPatch, "-", "")
				} else {
					lines[i] = pifPatch
				}
				replaced = true
			}
		case p.Kind == "system" && key == "system":
			if patchSix.MatchString(val) {
				lines[i], replaced = "system="+strings.ReplaceAll(pifPatch[:7], "-", ""), true
			}
		}
	}
	if !replaced {
		return []byte("all=" + pifPatch + "\n")
	}
	return []byte(strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n")
}
